/**
 * Get a timestamp suitable for use in the name of a reference, e.g. `20240131-235959-123`.
 * @param date The date.
 * @returns The timestamp.
 */
function getRefTimestamp(date: Date) {
	const pad = (n: number, length: number = 2) => n.toString().padStart(length, '0');
	return date.getFullYear() + pad(date.getMonth() + 1) + pad(date.getDate()) + '-' + pad(date.getHours()) + pad(date.getMinutes()) + pad(date.getSeconds()) + '-' + pad(date.getMilliseconds(), 3);
}

/**
 * Convert a string into a component that is valid within the name of a reference.
 * @param value The string.
 * @returns The reference name component.
 */
function toRefNameComponent(value: string) {
	return value.replace(/[^A-Za-z0-9._-]+/g, '-').replace(/\.{2,}/g, '.').replace(/^[.-]+|[.-]+$/g, '').replace(/\.lock$/, '');
}

/**
 * Quote a string as a single argument for the POSIX shell that Git uses to run editor commands (also on Windows).
 * @param value The string to quote.
 * @returns The quoted string.
 */
function shellQuote(value: string) {
	return '\'' + value.replace(/\\/g, '/').replace(/'/g, '\'\\\'\'') + '\'';
}

/**
 * Write content to a new file in a private temporary directory.
 * @param fileName The name of the file.
 * @param content The content of the file.
 * @returns The path of the file.
 */
function writeTempFile(fileName: string, content: string) {
	const filePath = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'easy-graph-')), fileName);
	fs.writeFileSync(filePath, content);
	return filePath;
}

/**
 * Remove a file created by `writeTempFile`, along with its temporary directory.
 * @param filePath The path of the file.
 */
function removeTempFile(filePath: string) {
	try {
		fs.unlinkSync(filePath);
		fs.rmdirSync(path.dirname(filePath));
	} catch { }
}

/**
 * Build a `GIT_SEQUENCE_EDITOR` command that changes the action of specific commits in the todo list of an interactive rebase from
 * `pick` to another action. The todo list abbreviates hashes (to a length that depends on `core.abbrev`) and may abbreviate `pick` to
 * `p` (`rebase.abbreviateCommands`), so a line matches when its hash is a prefix of one of the full hashes. The editor fails (aborting
 * the rebase before it changes anything) unless every commit was found.
 * @param action The new action (e.g. `drop` or `reword`).
 * @param hashes The full hashes of the commits.
 * @returns The command.
 */
export function rebaseTodoActionEditor(action: 'drop' | 'reword', hashes: ReadonlyArray<string>) {
	const program = [
		'BEGIN { n = split(hashes, list, ",") }',
		'($1 == "pick" || $1 == "p") && length($2) >= 4 {',
		'for (i = 1; i <= n; i++) if (index(list[i], $2) == 1) { found[i] = 1; $0 = action substr($0, length($1) + 1); break }',
		'}',
		'{ print }',
		'END { for (i = 1; i <= n; i++) if (!(i in found)) exit 1 }'
	].join(' ');
	// The hashes are validated as hexadecimal, and the program contains no single quotes, so both can be passed to the shell as they are
	return 'f() { awk -v action=' + action + ' -v hashes=' + hashes.filter((hash) => FULL_COMMIT_HASH_REGEXP.test(hash)).join(',') + ' \'' + program + '\' "$1" > "$1.easy-graph" && mv "$1.easy-graph" "$1"; }; f';
}


