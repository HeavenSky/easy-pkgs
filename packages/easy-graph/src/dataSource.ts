	/**
	 * Undo the last commit, keeping its changes staged (a soft reset of the current branch to the first parent of HEAD).
	 * @param repo The path of the repository.
	 * @returns The ErrorInfo from the executed command.
	 */
	public async undoLastCommit(repo: string): Promise<ErrorInfo> {
		const parents = await this.getCommitParents(repo, 'HEAD');
		if (parents === null) {
			return 'Unable to find the commit checked out (HEAD).';
		} else if (parents.length === 0) {
			return 'The last commit is the root commit of the repository, and can\'t be reset.';
		}
		return this.withBackup(repo, 'HEAD', 'undo-commit', () => this.runGitCommand(['reset', '--soft', parents[0]], repo));
	}

	/**
	 * Replace the message of a commit on the current branch. HEAD is amended, an older commit is reworded with an interactive rebase.
	 * @param repo The path of the repository.
	 * @param commitHash The hash of the commit.
	 * @param message The new message.
	 * @param noVerify If enabled, skip the commit hooks (e.g. pre-commit and commit-msg).
	 * @returns The ErrorInfo from the executed command.
	 */
	public async editCommitMessage(repo: string, commitHash: string, message: string, noVerify: boolean): Promise<ErrorInfo> {
		if (!FULL_COMMIT_HASH_REGEXP.test(commitHash)) {
			return 'Invalid commit hash.';
		}
		const head = await this.resolveCommit(repo, 'HEAD');
		if (head === null) {
			return 'Unable to find the commit checked out (HEAD).';
		} else if (head !== commitHash) {
			return this.rewordAncestorOfHead(repo, commitHash, message, noVerify);
		}

		// --only leaves any staged changes out of the amended commit, and --allow-empty also allows commits that don't change any files
		const args = ['commit', '--amend', '--only', '--allow-empty', '--cleanup=whitespace', '-m', message];
		args.push(...getSignArgs(repo));
		if (noVerify) args.push('--no-verify');
		return this.withBackup(repo, 'HEAD', 'edit-message', () => this.runGitCommand(args, repo));
	}

	/**
	 * Replace the message of an ancestor of HEAD, by rebasing the commits after its parent (keeping merge commits) with it reworded.
	 * @param repo The path of the repository.
	 * @param commitHash The full hash of the commit.
	 * @param message The new message.
	 * @param noVerify If enabled, skip the commit hooks that run while rewording (e.g. commit-msg).
	 * @returns The ErrorInfo from the executed command.
	 */
	private async rewordAncestorOfHead(repo: string, commitHash: string, message: string, noVerify: boolean): Promise<ErrorInfo> {
		const parents = await this.getCommitParents(repo, commitHash);
		if (parents === null || parents.length !== 1) {
			return 'The message of a merge commit or a root commit can only be edited when it is HEAD.';
		}
		const onCurrentBranch = await this.spawnGit(['merge-base', '--is-ancestor', commitHash, 'HEAD'], repo, () => true).catch(() => false);
		if (!onCurrentBranch) {
			return 'The commit is not on the current branch.';
		}
		const inProgressError = await this.getOperationInProgressError(repo).catch((error: string) => error);
		if (inProgressError !== null) {
			return inProgressError;
		}
		const status = await this.spawnGit(['status', '--porcelain', '--untracked-files=no'], repo, (stdout) => stdout.trim()).catch(() => null);
		if (status === null) {
			return 'Unable to check the repository for uncommitted changes.';
		} else if (status !== '') {
			return 'The repository has uncommitted changes. Please commit or stash them before editing the message of an older commit.';
		}

		const args = ['-c', 'commit.cleanup=whitespace'];
		// Rebase has no option to skip the commit hooks (e.g. commit-msg) that run when rewording, so point Git at an empty hooks directory instead
		const emptyHooksDir = noVerify ? fs.mkdtempSync(path.join(os.tmpdir(), 'easy-graph-hooks-')) : null;
		if (emptyHooksDir !== null) {
			args.push('-c', 'core.hooksPath=' + emptyHooksDir);
		}
		args.push('rebase', '-i', '--rebase-merges');
		args.push(...getSignArgs(repo));
		args.push(parents[0]);

		// The message is copied from a file by the editor command, so that its text never becomes part of a shell command
		const messageFile = writeTempFile('COMMIT_EDITMSG', message + '\n');
		const error = await this.withBackup(repo, 'HEAD', 'edit-message', () => this.runGitCommandWithEnv(args, repo, {
			GIT_SEQUENCE_EDITOR: rebaseTodoActionEditor('reword', [commitHash]),
			GIT_EDITOR: 'cp ' + shellQuote(messageFile)
		}));
		removeTempFile(messageFile);
		if (emptyHooksDir !== null) {
			try {
				fs.rmdirSync(emptyHooksDir);
			} catch { }
		}
		return error;
	}

	/**
	 * Add, replace or remove the notes (`git notes`, of the default notes ref) of a commit.
	 * @param repo The path of the repository.
	 * @param commitHash The commit hash.
	 * @param notes The new notes, an empty string removes the notes.
	 * @returns The ErrorInfo from the executed command.
	 */
	public setCommitNotes(repo: string, commitHash: string, notes: string): Promise<ErrorInfo> {
		if (notes.trim() === '') {
			return this.runGitCommand(['notes', 'remove', '--ignore-missing', commitHash], repo);
		}
		if (this.gitExecutable === null) {
			return Promise.resolve(UNABLE_TO_FIND_GIT_MSG);
		}

		// The notes are passed via stdin, so that they are never interpolated into a command
		const args = ['notes', 'add', '-f', '-F', '-', commitHash];
		const child = cp.spawn(this.gitExecutable.path, args, {
			cwd: repo,
			env: Object.assign({}, process.env, this.askpassEnv)
		});
		const result = resolveSpawnOutput(child).then(([status, stdout, stderr]) => {
			return status.code !== 0 ? getErrorMessage(status.error, stdout, stderr) : null;
		}, (errorMessage) => errorMessage);
		if (child.stdin) {
			child.stdin.on('error', () => { });
			child.stdin.end(notes);
		}
		this.logger.logCmd('git', args);
		return result;
	}


