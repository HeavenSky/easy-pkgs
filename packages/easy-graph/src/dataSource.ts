/**
 * Parse a Git config boolean.
 * @param value The value of the Git config key, or undefined if it isn't set.
 * @returns The boolean, or NULL if it isn't set or isn't a boolean.
 */
function parseGitBoolean(value: string | undefined) {
	if (typeof value === 'undefined') return null;
	const normalised = value.trim().toLowerCase();
	if (normalised === '' || normalised === 'true' || normalised === 'yes' || normalised === 'on' || normalised === '1') return true;
	if (normalised === 'false' || normalised === 'no' || normalised === 'off' || normalised === '0') return false;
	return null;
}

